import { describe, expect, it } from 'vitest'
import { numberToWordsRuDecimal } from '@/lib/legacy/decimalToWords'

describe('Russian decimal grammar (feminine numerator + fraction declension)', () => {
	const cases: Array<[number, string]> = [
		[0.1, 'ноль целых одна десятая'],
		[0.2, 'ноль целых две десятых'],
		[0.01, 'ноль целых одна сотая'],
		[0.02, 'ноль целых две сотых'],
		[0.001, 'ноль целых одна тысячная'],
		[0.000001, 'ноль целых одна миллионная'],
		[0.000002, 'ноль целых две миллионных'],
		[0.000011, 'ноль целых одиннадцать миллионных'],
		[0.000021, 'ноль целых двадцать одна миллионная'],
		[0.000022, 'ноль целых двадцать две миллионных'],
		[
			0.123456,
			'ноль целых сто двадцать три тысячи четыреста пятьдесят шесть миллионных',
		],
	]

	it.each(cases)('%s → %s', (value, expected) => {
		expect(numberToWordsRuDecimal(value, { format: 'numeric' })).toBe(
			expected,
		)
	})

	it('agrees feminine whole-part (целая/целых) with the integer', () => {
		// Independent whole-part matrix: 1 / 2–4 / 5+ / 11–14 / 21–24 / 101–104.
		// «целая» only for form=one; feminine одна/две for ones digit.
		const wholeCases: Array<[number, string]> = [
			[1.5, 'одна целая пять десятых'],
			[1.5, 'одна целая пять десятых'], // 1.50 as Number → same as 1.5
			[2.5, 'две целых пять десятых'],
			[3.5, 'три целых пять десятых'],
			[4.5, 'четыре целых пять десятых'],
			[5.5, 'пять целых пять десятых'],
			[11.5, 'одиннадцать целых пять десятых'],
			[12.5, 'двенадцать целых пять десятых'],
			[13.5, 'тринадцать целых пять десятых'],
			[14.5, 'четырнадцать целых пять десятых'],
			[21.05, 'двадцать одна целая пять сотых'],
			[22.05, 'двадцать две целых пять сотых'],
			[23.05, 'двадцать три целых пять сотых'],
			[24.05, 'двадцать четыре целых пять сотых'],
			[101.5, 'сто одна целая пять десятых'],
			[102.5, 'сто две целых пять десятых'],
			[103.5, 'сто три целых пять десятых'],
			[104.5, 'сто четыре целых пять десятых'],
		]
		for (const [value, expected] of wholeCases) {
			expect(
				numberToWordsRuDecimal(value, { format: 'numeric' }),
				String(value),
			).toBe(expected)
		}
	})

	/**
	 * Boundary matrix: every supported precision (1–6) × one / few / many.
	 * Few (2–4) must use genitive plural, same as many — never nominative.
	 */
	it('covers one/few/many for every fractional precision 1–6', () => {
		const matrix: Array<[number, string]> = [
			// precision 1
			[0.1, 'ноль целых одна десятая'],
			[0.2, 'ноль целых две десятых'],
			[0.3, 'ноль целых три десятых'],
			[0.4, 'ноль целых четыре десятых'],
			[0.5, 'ноль целых пять десятых'],
			// precision 2
			[0.01, 'ноль целых одна сотая'],
			[0.02, 'ноль целых две сотых'],
			[0.05, 'ноль целых пять сотых'],
			[0.12, 'ноль целых двенадцать сотых'],
			// precision 3
			[0.001, 'ноль целых одна тысячная'],
			[0.002, 'ноль целых две тысячных'],
			[0.005, 'ноль целых пять тысячных'],
			[0.014, 'ноль целых четырнадцать тысячных'],
			// precision 4
			[0.0001, 'ноль целых одна десятитысячная'],
			[0.0002, 'ноль целых две десятитысячных'],
			[0.0005, 'ноль целых пять десятитысячных'],
			// precision 5
			[0.00001, 'ноль целых одна стотысячная'],
			[0.00002, 'ноль целых две стотысячных'],
			[0.00005, 'ноль целых пять стотысячных'],
			// precision 6
			[0.000001, 'ноль целых одна миллионная'],
			[0.000002, 'ноль целых две миллионных'],
			[0.000003, 'ноль целых три миллионных'],
			[0.000004, 'ноль целых четыре миллионных'],
			[0.000005, 'ноль целых пять миллионных'],
			[0.000012, 'ноль целых двенадцать миллионных'],
			[0.000013, 'ноль целых тринадцать миллионных'],
			[0.000014, 'ноль целых четырнадцать миллионных'],
			[0.000022, 'ноль целых двадцать две миллионных'],
		]

		for (const [value, expected] of matrix) {
			expect(
				numberToWordsRuDecimal(value, { format: 'numeric' }),
				String(value),
			).toBe(expected)
		}
	})
})
